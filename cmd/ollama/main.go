	// 				fmt.Printf("[getSurroundingBlocksOfType] Skipping block at (%d, %d, %d) with name '%s' (does not contain '%s')\n", int(x)+ix, int(y)+iy, int(z)+iz, blockName, filterKeep)
	// 				continue
