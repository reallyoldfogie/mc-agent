type tmpSlot struct {
	SlotIndex int    `json:"slot_index"`
	ID        int32  `json:"id"`
	Count     int32  `json:"count"`
	Name      string `json:"name"`
}

func buildGameStateString(goal string, agent models.Agent, blocks []BlockPos, radius int, lastResult string, lastPath *models.Path) string {
	pos, initialized := agent.GetPositionSimple()
	if !initialized {
		return ""
	}
	x, y, z := pos.X, pos.Y, pos.Z

	const miningRange = 3.0

	itemMgr := agent.GetItemManager()
	inventoryRaw := agent.GetInventory().GetSlots()
	inventory := []tmpSlot{}
	for idx, slot := range inventoryRaw {
		if slot.ID != 0 {
			itemName := itemMgr.GetItemNameByID(int32(slot.ID))
			log.Printf("Inventory slot %d: %s x %d", idx, itemName, slot.Count)
			inventory = append(inventory, tmpSlot{SlotIndex: idx, ID: int32(slot.ID), Count: int32(slot.Count), Name: itemName})
		} else {
			log.Printf("Inventory slot %d: empty", idx)
		}
	}
	inventoryRawStr, _ := json.Marshal(inventory)
	inventoryStr := string(inventoryRawStr)

	// Categorize blocks by mining range
	mineableBlocks := []BlockPos{}
	pathfindingBlocks := []BlockPos{}
	for _, b := range blocks {
		if b.Distance <= miningRange {
			mineableBlocks = append(mineableBlocks, b)
		} else {
			pathfindingBlocks = append(pathfindingBlocks, b)
		}
	}

	// Sort each category by distance
	sort.Slice(mineableBlocks, func(i, j int) bool {
		return mineableBlocks[i].Distance < mineableBlocks[j].Distance
	})
	sort.Slice(pathfindingBlocks, func(i, j int) bool {
		return pathfindingBlocks[i].Distance < pathfindingBlocks[j].Distance
	})

	mineableStr := "[]"
	if len(mineableBlocks) > 0 {
		mineableBytes, _ := json.Marshal(mineableBlocks)
		mineableStr = string(mineableBytes)
	}

	pathfindingStr := "[]"
	if len(pathfindingBlocks) > 0 {
		pathfindingBytes, _ := json.Marshal(pathfindingBlocks)
		pathfindingStr = string(pathfindingBytes)
	}

	fmt.Printf("[buildPrompt] Mineable blocks (≤%.1f): %v\n", miningRange, mineableStr)
	fmt.Printf("[buildPrompt] Pathfinding blocks (>%.1f): %v\n", miningRange, pathfindingStr)

	pathInfo := "none"
	if lastPath != nil && lastPath.Found {
		pathInfo = fmt.Sprintf("from (%.1f, %.1f, %.1f) to (%.1f, %.1f, %.1f), %d steps — ready to execute",
			lastPath.StartPos.X, lastPath.StartPos.Y, lastPath.StartPos.Z,
			lastPath.GoalPos.X, lastPath.GoalPos.Y, lastPath.GoalPos.Z,
			len(lastPath.Steps))
	}

	mineableBlocksDisplay := mineableStr
	if mineableStr == "[]" {
		mineableBlocksDisplay = "(none available)"
	}

	pathfindingBlocksDisplay := pathfindingStr
	if pathfindingStr == "[]" {
		pathfindingBlocksDisplay = "(none available)"
	}

	return fmt.Sprintf(`Goal: %s

Current State:
- Current Position: (X: %.2f, Y: %.2f, Z: %.2f)
- Precomputed Path: %s
- Last Result: %s
- Current Inventory: %s

MINEABLE BLOCKS (distance ≤ 3 blocks, mine immediately):
%s

PATHFINDING BLOCKS (distance > 3 blocks, pathfind to them):
%s

Strategy:
- If mineable blocks exist (distance ≤ 3), mine the closest one immediately
- Only pathfind to blocks when NO mineable blocks exist
- If a precomputed path is ready to execute, execute it next unless new mineable blocks appeared
`, goal, x, y, z, pathInfo, lastResult, inventoryStr, mineableBlocksDisplay, pathfindingBlocksDisplay)
}

